CREATE DATABASE IF NOT EXISTS sepe CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sepe;
SET NAMES utf8mb4;
DROP TABLE IF EXISTS enfermedad_sintoma;
DROP TABLE IF EXISTS enfermedades;
DROP TABLE IF EXISTS sintomas;
DROP TABLE IF EXISTS referencias;
CREATE TABLE referencias (id INT AUTO_INCREMENT PRIMARY KEY, institucion VARCHAR(100) NOT NULL, titulo VARCHAR(200) NOT NULL, url VARCHAR(500) NOT NULL) ENGINE=InnoDB;
CREATE TABLE enfermedades (id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(150) NOT NULL UNIQUE, referencia_id INT NOT NULL, FOREIGN KEY (referencia_id) REFERENCES referencias(id)) ENGINE=InnoDB;
CREATE TABLE sintomas (id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(150) NOT NULL UNIQUE, categoria VARCHAR(80) NOT NULL) ENGINE=InnoDB;
CREATE TABLE enfermedad_sintoma (enfermedad_id INT NOT NULL, sintoma_id INT NOT NULL, peso TINYINT UNSIGNED NOT NULL, PRIMARY KEY(enfermedad_id,sintoma_id), FOREIGN KEY(enfermedad_id) REFERENCES enfermedades(id), FOREIGN KEY(sintoma_id) REFERENCES sintomas(id), CHECK(peso BETWEEN 1 AND 5)) ENGINE=InnoDB;
